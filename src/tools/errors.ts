export function humanError(code: string, extra?: Record<string, unknown>): string {
  if (code === "EXCEPTION") return `Ошибка After Effects: ${String(extra?.message ?? "неизвестно")}`;
  return messages[code] ?? `Ошибка: ${code}`;
}
